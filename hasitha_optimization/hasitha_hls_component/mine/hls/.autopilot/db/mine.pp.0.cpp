static bool hash_below_target(const uint8_t raw[32], const uint32_t target[8]) {
#pragma HLS INLINE

    COMPARE_HASH:
        for (int i = 0; i < 32; i++) {
            uint8_t hb = raw[31 - i];

            int word_index = i >> 2;
            int byte_index = i & 3;

            uint8_t tb = static_cast<uint8_t>(
                target[word_index] >> (byte_index * 8)
            );

            if (hb < tb) {
                return true;
            }

            if (hb > tb) {
                return false;
            }
        }

        return false;
    }




